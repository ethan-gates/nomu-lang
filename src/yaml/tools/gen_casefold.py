#!/usr/bin/env python3
"""Generates sources/CaseFolding.swift: Unicode simple case folding (the C and S mappings of CaseFolding.txt),
which duplicate-key detection uses (spec §6).

Reads the folding from the system ICU (macOS libicucore, through u_foldCase with the default options), so the
table matches that ICU's Unicode version. Run from anywhere:

    python3 src/yaml/tools/gen_casefold.py
"""
import ctypes
import os

icu = ctypes.CDLL("/usr/lib/libicucore.dylib")
icu.u_foldCase.restype = ctypes.c_int32
icu.u_foldCase.argtypes = [ctypes.c_int32, ctypes.c_uint32]
version = (ctypes.c_uint8 * 4)()
icu.u_getUnicodeVersion(version)

pairs = []
for c in range(0x80, 0x110000):
    if 0xD800 <= c <= 0xDFFF:
        continue
    f = icu.u_foldCase(c, 0)
    if f != c:
        pairs.append((c, f))

lines = []
for i in range(0, len(pairs), 4):
    row = ", ".join("0x%06X_%06X" % p for p in pairs[i:i + 4])
    lines.append("    " + row + ",")

out = f"""// Generated by tools/gen_casefold.py from ICU's Unicode {version[0]}.{version[1]}.{version[2]}; do not edit.
//
// Unicode simple case folding (the C and S mappings of CaseFolding.txt) for scalars above ASCII, as sorted
// pairs packed `from << 24 | to`. ASCII folds A–Z to a–z without the table.

let caseFoldingPairs: [UInt64] = [
{chr(10).join(lines)}
]
"""
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "sources", "CaseFolding.swift")
with open(path, "w") as f:
    f.write(out)
print(f"{len(pairs)} mappings, Unicode {version[0]}.{version[1]}.{version[2]}")
